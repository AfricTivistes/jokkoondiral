const TEXTES: Record<string, Textes> = { fr: FR, en: EN };

let courante = "fr";
export const setLangue = (l: string) => {
  courante = TEXTES[l] ? l : "fr";
  document.documentElement.lang = courante;
};
export const langue = () => courante;
export const languesInterface = () => Object.keys(TEXTES);

/** Texte de l'interface : tr("erreurs.obligatoire"), avec variables {x}. */
export function tr(cle: string, vars: Record<string, string | number> = {}): string {
  const lire = (base: unknown) => cle.split(".").reduce<unknown>((o, k) => (o as Record<string, unknown>)?.[k], base);
  const v = lire(TEXTES[courante]) ?? lire(FR) ?? cle;
  return String(v).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
